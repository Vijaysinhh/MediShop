export function repairPdfMojibake(value: string) {
  if (!mojibakePattern.test(value)) return value;

  try {
    const bytes = Uint8Array.from(value, (char) => {
      const charCode = char.charCodeAt(0);
      return windows1252Bytes.get(char) ?? (charCode <= 0xff ? charCode : 0x3f);
    });
    return new TextDecoder("utf-8", { fatal: false }).decode(bytes);
  } catch {
    return value;
  }
}

